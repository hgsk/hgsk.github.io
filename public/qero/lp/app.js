let language = localStorage.getItem("qero.lp.lang") ||
  (navigator.language.toLowerCase().startsWith("ja") ? "ja" : "en");

function t(key) {
  return copy[language][key] ?? copy.ja[key] ?? key;
}

function renderLanguage() {
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.setAttribute("placeholder", t(node.dataset.i18nPlaceholder));
  });
  const toggle = document.querySelector("#lang-toggle");
  toggle.textContent = language === "ja" ? "EN" : "JA";
}

document.querySelector("#lang-toggle").addEventListener("click", () => {
  language = language === "ja" ? "en" : "ja";
  localStorage.setItem("qero.lp.lang", language);
  renderLanguage();
});

document.querySelectorAll("[data-pilot]").forEach((link) => {
  link.addEventListener("click", () => {
    document.querySelector("#pilot").value = link.dataset.pilot;
  });
});

document.querySelector("#consult-form").addEventListener("submit", async (event) => {
  event.preventDefault();
  const org = document.querySelector("#org").value.trim() || "—";
  const painSelect = document.querySelector("#pain");
  const pilotSelect = document.querySelector("#pilot");
  const context = document.querySelector("#context").value.trim() || "—";
  const draft = [
    t("draftSubject"),
    "",
    t("draftIntro"),
    "",
    `${t("draftOrg")}: ${org}`,
    `${t("draftPain")}: ${painSelect.options[painSelect.selectedIndex].text}`,
    `${t("draftPilot")}: ${pilotSelect.options[pilotSelect.selectedIndex].text}`,
    `${t("draftContext")}: ${context}`,
    "",
    t("draftClose"),
  ].join("\n");
  const status = document.querySelector("#copy-status");
  try {
    await navigator.clipboard.writeText(draft);
    status.textContent = t("copied");
  } catch {
    status.textContent = t("copyFailed");
  }
});

renderLanguage();
